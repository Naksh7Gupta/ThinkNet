"""Generate reusable Python wrappers for validated ThinkNet graphs.

The exported file is designed to run from the ThinkNet repository root and reuses
the same tested compiler as the API. It embeds the graph specification so users
can version-control and edit the architecture without reconstructing the JSON.
"""
from __future__ import annotations

import json
from typing import Any


def generate_python_source(graph_spec: dict[str, Any]) -> str:
    """Return Python source that rebuilds a graph through ThinkNet's compiler."""
    serialized = json.dumps(graph_spec, indent=4, sort_keys=True)
    # A repr-encoded JSON string safely preserves quotes and newlines in source.
    encoded = repr(serialized)
    return f'''# Generated by ThinkNet. Review and test before using in production.
# Run from the ThinkNet repository root:
#   python exported_model.py
from __future__ import annotations

import json
import torch
from torch import nn

from services.backend.thinknet_backend_core import GraphDef, CompiledGraph, validate_graph

GRAPH_SPEC = json.loads({encoded})


def build_model() -> nn.Module:
    """Build the architecture from its embedded graph specification."""
    graph = GraphDef.model_validate(GRAPH_SPEC)
    errors = validate_graph(graph)
    if errors:
        raise ValueError("Invalid ThinkNet graph: " + "; ".join(errors))
    return CompiledGraph(graph)


class GeneratedThinkNetModel(nn.Module):
    """Reusable PyTorch module generated from a ThinkNet graph."""
    def __init__(self) -> None:
        super().__init__()
        self.graph_model = build_model()

    def forward(self, inputs: torch.Tensor, extra_inputs=None):
        return self.graph_model(inputs, extra_inputs=extra_inputs)


if __name__ == "__main__":
    model = build_model()
    print("ThinkNet graph loaded successfully")
    print(f"Architecture: {{GRAPH_SPEC.get('name', 'untitled_architecture')}}")
    print(f"Nodes: {{len(GRAPH_SPEC.get('nodes', []))}}")
    print(f"Parameters: {{sum(p.numel() for p in model.parameters()):,}}")
    print("Create an input tensor matching the Input node's configured sample shape,")
    print("then call model(input_tensor) to run inference.")
'''
