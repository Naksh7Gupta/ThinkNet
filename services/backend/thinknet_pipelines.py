"""Small, local-first DAG runner for reusable data preparation components.

The runner deliberately uses artifact references between components. It is not a
replacement for the existing PyTorch architecture compiler or managed trainer.
"""
from __future__ import annotations

import csv
import json
import os
import random
import shutil
import uuid
from collections import defaultdict, deque
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field

ROOT = Path(__file__).resolve().parents[2]
ARTIFACT_ROOT = Path(os.environ.get(
    "THINKNET_PIPELINE_ARTIFACT_DIR", str(ROOT / "training_output" / "pipeline_artifacts")
)).expanduser().resolve()
MAX_CSV_BYTES = 50 * 1024 * 1024
router = APIRouter(prefix="/api/v1/pipelines", tags=["pipelines"])


class PipelineNode(BaseModel):
    id: str = Field(min_length=1, max_length=100)
    type: str = Field(min_length=1, max_length=100)
    config: dict[str, Any] = Field(default_factory=dict)


class PipelineEdge(BaseModel):
    source: str
    target: str
    source_port: str = "output"
    target_port: str = "input"


class PipelineGraph(BaseModel):
    name: str = Field(default="untitled_pipeline", max_length=120)
    nodes: list[PipelineNode]
    edges: list[PipelineEdge] = Field(default_factory=list)


class PipelineRunRequest(BaseModel):
    graph: PipelineGraph
    seed: int = 42


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _artifact_path(artifact_id: str) -> Path:
    # IDs are generated by ThinkNet; never accept an arbitrary path from a graph edge.
    if not artifact_id or any(ch not in "abcdefghijklmnopqrstuvwxyz0123456789-" for ch in artifact_id):
        raise ValueError("Invalid artifact reference.")
    path = (ARTIFACT_ROOT / f"{artifact_id}.csv").resolve()
    if path.parent != ARTIFACT_ROOT:
        raise ValueError("Artifact reference escapes the artifact store.")
    return path


def _write_csv(rows: list[dict[str, Any]], columns: list[str]) -> dict[str, Any]:
    ARTIFACT_ROOT.mkdir(parents=True, exist_ok=True)
    artifact_id = uuid.uuid4().hex
    path = _artifact_path(artifact_id)
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    return {"artifact_id": artifact_id, "kind": "csv", "columns": columns, "rows": len(rows)}


def _read_csv(ref: dict[str, Any]) -> tuple[list[dict[str, str]], list[str]]:
    if not isinstance(ref, dict) or ref.get("kind") != "csv":
        raise ValueError("Expected a ThinkNet CSV artifact reference.")
    path = _artifact_path(str(ref.get("artifact_id", "")))
    if not path.is_file():
        raise ValueError(f"Artifact '{ref.get('artifact_id')}' does not exist.")
    with path.open("r", newline="", encoding="utf-8-sig") as stream:
        reader = csv.DictReader(stream)
        columns = list(reader.fieldnames or [])
        rows = list(reader)
    return rows, columns


def _load_csv(config: dict[str, Any], _inputs: dict[str, Any], _context: dict[str, Any]) -> dict[str, Any]:
    source = Path(str(config.get("path", ""))).expanduser()
    if not source.is_file():
        raise ValueError("Choose an existing local CSV file in the Load CSV node.")
    if source.stat().st_size > MAX_CSV_BYTES:
        raise ValueError(f"CSV exceeds the {MAX_CSV_BYTES // (1024 * 1024)} MB MVP limit.")
    delimiter = str(config.get("delimiter", ","))
    if len(delimiter) != 1:
        raise ValueError("CSV delimiter must be exactly one character.")
    with source.open("r", newline="", encoding="utf-8-sig") as stream:
        reader = csv.DictReader(stream, delimiter=delimiter)
        columns = list(reader.fieldnames or [])
        if not columns:
            raise ValueError("CSV must contain a header row.")
        rows = list(reader)
    if not rows:
        raise ValueError("CSV contains no data rows.")
    ref = _write_csv(rows, columns)
    return {"dataset": ref}


def _inspect(_config: dict[str, Any], inputs: dict[str, Any], _context: dict[str, Any]) -> dict[str, Any]:
    rows, columns = _read_csv(inputs["dataset"])
    missing = {column: sum(row.get(column, "") == "" for row in rows) for column in columns}
    preview = rows[:5]
    return {"dataset": inputs["dataset"], "report": {
        "rows": len(rows), "columns": columns, "missing_values": missing, "preview": preview,
    }}


def _select_xy(config: dict[str, Any], inputs: dict[str, Any], _context: dict[str, Any]) -> dict[str, Any]:
    rows, columns = _read_csv(inputs["dataset"])
    features = config.get("feature_columns")
    target = config.get("target_column")
    if target is not None and not isinstance(target, str):
        raise ValueError("target_column must be a column name or null.")
    if not isinstance(features, list) or not features or any(not isinstance(c, str) for c in features):
        raise ValueError("feature_columns must be a non-empty list of column names.")
    if len(features) != len(set(features)):
        raise ValueError("feature_columns must not contain duplicates.")
    missing = [c for c in features + ([target] if target else []) if c not in columns]
    if missing:
        raise ValueError(f"Unknown CSV column(s): {', '.join(missing)}.")
    x_rows = [{column: row.get(column, "") for column in features} for row in rows]
    result = {"X": _write_csv(x_rows, features)}
    if target:
        y_rows = [{target: row.get(target, "")} for row in rows]
        result["Y"] = _write_csv(y_rows, [target])
    result["metadata"] = {"row_count": len(rows), "feature_columns": features, "target_column": target}
    return result


def _split_xy(config: dict[str, Any], inputs: dict[str, Any], context: dict[str, Any]) -> dict[str, Any]:
    x_rows, x_columns = _read_csv(inputs["X"])
    y_ref = inputs.get("Y")
    y_rows, y_columns = _read_csv(y_ref) if y_ref is not None else (None, [])
    if y_rows is not None and len(x_rows) != len(y_rows):
        raise ValueError("X and Y row counts differ; refusing to split misaligned data.")
    fraction = float(config.get("validation_fraction", 0.2))
    test_fraction = float(config.get("test_fraction", 0.0))
    if not 0 <= fraction < 1 or not 0 <= test_fraction < 1 or fraction + test_fraction >= 1:
        raise ValueError("Validation and test fractions must be non-negative and sum to less than 1.")
    indices = list(range(len(x_rows)))
    random.Random(context["seed"]).shuffle(indices)
    val_count = int(len(indices) * fraction)
    test_count = int(len(indices) * test_fraction)
    train_count = len(indices) - val_count - test_count
    groups = {
        "train": indices[:train_count],
        "validation": indices[train_count:train_count + val_count],
        "test": indices[train_count + val_count:],
    }
    outputs: dict[str, Any] = {}
    for split, positions in groups.items():
        outputs[f"X_{split}"] = _write_csv([x_rows[i] for i in positions], x_columns)
        if y_rows is not None:
            outputs[f"Y_{split}"] = _write_csv([y_rows[i] for i in positions], y_columns)
    outputs["metadata"] = {
        "counts": {name: len(positions) for name, positions in groups.items()},
        "has_targets": y_rows is not None,
        "seed": context["seed"],
    }
    return outputs


# Metadata and execution live together so the UI can render only real components.
COMPONENTS: dict[str, dict[str, Any]] = {
    "csv.load": {"inputs": {}, "outputs": {"dataset": "dataset_ref"}, "run": _load_csv},
    "dataset.inspect": {"inputs": {"dataset": "dataset_ref"}, "outputs": {
        "dataset": "dataset_ref", "report": "report"}, "run": _inspect},
    "dataset.select_xy": {"inputs": {"dataset": "dataset_ref"}, "outputs": {
        "X": "dataset_ref", "Y": "dataset_ref?", "metadata": "metadata"}, "run": _select_xy},
    "dataset.split_xy": {"inputs": {"X": "dataset_ref", "Y": "dataset_ref?"}, "outputs": {
        "X_train": "dataset_ref", "X_validation": "dataset_ref", "X_test": "dataset_ref",
        "Y_train": "dataset_ref?", "Y_validation": "dataset_ref?", "Y_test": "dataset_ref?",
        "metadata": "metadata"}, "run": _split_xy},
}


def component_catalog() -> list[dict[str, Any]]:
    return [{key: value for key, value in item.items() if key != "run"} | {"type": name}
            for name, item in COMPONENTS.items()]


def _order(graph: PipelineGraph) -> tuple[list[PipelineNode], dict[str, list[PipelineEdge]]]:
    if not graph.nodes:
        raise ValueError("Pipeline must contain at least one component.")
    ids = [node.id for node in graph.nodes]
    if len(ids) != len(set(ids)):
        raise ValueError("Pipeline node IDs must be unique.")
    by_id = {node.id: node for node in graph.nodes}
    for node in graph.nodes:
        if node.type not in COMPONENTS:
            raise ValueError(f"Unknown or non-executable component '{node.type}'.")
    incoming: dict[str, list[PipelineEdge]] = defaultdict(list)
    outgoing: dict[str, list[str]] = defaultdict(list)
    degree = {node.id: 0 for node in graph.nodes}
    seen: set[tuple[str, str, str, str]] = set()
    for edge in graph.edges:
        if edge.source not in by_id or edge.target not in by_id:
            raise ValueError(f"Edge references an unknown node: {edge.source} → {edge.target}.")
        if edge.source == edge.target:
            raise ValueError(f"Self-loop at node '{edge.source}' is not allowed.")
        key = (edge.source, edge.source_port, edge.target, edge.target_port)
        if key in seen:
            raise ValueError("Duplicate pipeline edges are not allowed.")
        seen.add(key)
        incoming[edge.target].append(edge)
        outgoing[edge.source].append(edge.target)
        degree[edge.target] += 1
    ready = deque(node.id for node in graph.nodes if degree[node.id] == 0)
    ordered: list[PipelineNode] = []
    while ready:
        node_id = ready.popleft()
        ordered.append(by_id[node_id])
        for target in outgoing[node_id]:
            degree[target] -= 1
            if degree[target] == 0:
                ready.append(target)
    if len(ordered) != len(graph.nodes):
        raise ValueError("Pipeline contains a cycle; only directed acyclic graphs are supported.")
    for node in graph.nodes:
        component = COMPONENTS.get(node.type)
        if component is None:
            raise ValueError(f"Unknown or non-executable component '{node.type}'.")
        wired = {edge.target_port for edge in incoming[node.id]}
        required = {port for port, kind in component["inputs"].items() if not kind.endswith("?")}
        missing = required - wired
        if missing:
            raise ValueError(f"Node '{node.id}' is missing required input(s): {', '.join(sorted(missing))}.")
        valid_ports = set(component["inputs"])
        unknown = wired - valid_ports
        if unknown:
            raise ValueError(f"Node '{node.id}' has unknown input port(s): {', '.join(sorted(unknown))}.")
        for edge in incoming[node.id]:
            source_component = COMPONENTS[by_id[edge.source].type]
            if edge.source_port not in source_component["outputs"]:
                raise ValueError(f"Node '{edge.source}' has no output port '{edge.source_port}'.")
            source_kind = source_component["outputs"][edge.source_port].rstrip("?")
            target_kind = component["inputs"][edge.target_port].rstrip("?")
            if source_kind != target_kind:
                raise ValueError(
                    f"Incompatible connection {edge.source}.{edge.source_port} ({source_kind}) "
                    f"→ {node.id}.{edge.target_port} ({target_kind})."
                )
            if edge.target_port in {e.target_port for e in incoming[node.id] if e is not edge}:
                raise ValueError(f"Input port '{edge.target_port}' on '{node.id}' can only have one connection.")
    return ordered, incoming


def execute_pipeline(graph: PipelineGraph, seed: int = 42) -> dict[str, Any]:
    ordered, incoming = _order(graph)
    context = {"seed": int(seed), "run_id": uuid.uuid4().hex}
    values: dict[str, dict[str, Any]] = {}
    records: list[dict[str, Any]] = []
    for node in ordered:
        component = COMPONENTS[node.type]
        inputs = {
            edge.target_port: values[edge.source][edge.source_port]
            for edge in incoming[node.id]
        }
        started = _now()
        try:
            outputs = component["run"](node.config, inputs, context)
            missing_outputs = set(outputs) - set(component["outputs"])
            if missing_outputs:
                raise ValueError(f"Component returned undeclared output(s): {', '.join(sorted(missing_outputs))}.")
            values[node.id] = outputs
            records.append({"node_id": node.id, "type": node.type, "status": "completed",
                            "started_at": started, "finished_at": _now()})
        except Exception as exc:
            records.append({"node_id": node.id, "type": node.type, "status": "failed",
                            "started_at": started, "finished_at": _now(), "error": str(exc)})
            failure = {"run_id": context["run_id"], "name": graph.name, "status": "failed",
                       "nodes": records, "error": f"Node '{node.id}' failed: {exc}"}
            ARTIFACT_ROOT.mkdir(parents=True, exist_ok=True)
            (ARTIFACT_ROOT / f"run-{context['run_id']}.json").write_text(
                json.dumps(failure, ensure_ascii=False, indent=2), encoding="utf-8"
            )
            failure["run_record"] = f"run-{context['run_id']}.json"
            return failure
    ARTIFACT_ROOT.mkdir(parents=True, exist_ok=True)
    result = {"run_id": context["run_id"], "name": graph.name, "status": "completed",
              "nodes": records, "outputs": values}
    run_path = ARTIFACT_ROOT / f"run-{context['run_id']}.json"
    run_path.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    result["run_record"] = run_path.name
    return result


@router.get("/components")
def list_pipeline_components():
    return {"components": component_catalog()}


@router.post("/validate")
def validate_pipeline(payload: PipelineGraph):
    try:
        ordered, _ = _order(payload)
        return {"valid": True, "node_count": len(payload.nodes),
                "edge_count": len(payload.edges), "execution_order": [node.id for node in ordered]}
    except ValueError as exc:
        return {"valid": False, "errors": [str(exc)]}


@router.post("/run")
def run_pipeline(payload: PipelineRunRequest):
    try:
        return execute_pipeline(payload.graph, payload.seed)
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc


# Additional local-first adapters and project persistence. These components emit
# the same artifact-reference contract as the CSV path, so the graph runner stays shared.
import wave
from datetime import datetime, timezone


def _load_text(config: dict[str, Any], _inputs: dict[str, Any], _context: dict[str, Any]) -> dict[str, Any]:
    source = Path(str(config.get("path", ""))).expanduser()
    if not source.is_file():
        raise ValueError("Choose an existing UTF-8 text file.")
    if source.stat().st_size > MAX_CSV_BYTES:
        raise ValueError("Text file exceeds the 50 MiB MVP limit.")
    text = source.read_text(encoding="utf-8-sig")
    if not text.strip():
        raise ValueError("Text file is empty.")
    mode = str(config.get("split", "lines"))
    documents = [line.strip() for line in text.splitlines() if line.strip()] if mode == "lines" else [text]
    if not documents:
        raise ValueError("No non-empty text documents were found.")
    rows = [{"text": item, "label": ""} for item in documents]
    return {"dataset": _write_csv(rows, ["text", "label"]),
            "metadata": {"modality": "text", "documents": len(rows), "source_name": source.name}}


def _load_image_folder(config: dict[str, Any], _inputs: dict[str, Any], _context: dict[str, Any]) -> dict[str, Any]:
    root = Path(str(config.get("path", ""))).expanduser()
    if not root.is_dir():
        raise ValueError("Choose an image dataset directory with one subdirectory per class.")
    allowed = {".png", ".jpg", ".jpeg", ".bmp", ".webp"}
    rows = []
    for class_dir in sorted(p for p in root.iterdir() if p.is_dir()):
        for file in sorted(p for p in class_dir.rglob("*") if p.is_file() and p.suffix.lower() in allowed):
            rows.append({"path": str(file.resolve()), "label": class_dir.name})
    if not rows:
        raise ValueError("No supported images found. Expected class-name subfolders.")
    return {"dataset": _write_csv(rows, ["path", "label"]),
            "metadata": {"modality": "image", "images": len(rows), "classes": sorted({r["label"] for r in rows})}}


def _load_audio_folder(config: dict[str, Any], _inputs: dict[str, Any], _context: dict[str, Any]) -> dict[str, Any]:
    root = Path(str(config.get("path", ""))).expanduser()
    if not root.is_dir():
        raise ValueError("Choose an audio dataset directory with one subdirectory per class.")
    rows = []
    for class_dir in sorted(p for p in root.iterdir() if p.is_dir()):
        for file in sorted(p for p in class_dir.rglob("*.wav") if p.is_file()):
            try:
                with wave.open(str(file), "rb") as audio:
                    frames, rate = audio.getnframes(), audio.getframerate()
                    channels = audio.getnchannels()
            except (wave.Error, EOFError) as exc:
                raise ValueError(f"Invalid WAV file: {file.name}") from exc
            if rate <= 0 or frames <= 0:
                continue
            rows.append({"path": str(file.resolve()), "label": class_dir.name,
                         "sample_rate": rate, "channels": channels, "duration_seconds": frames / rate})
    if not rows:
        raise ValueError("No valid WAV files found in class-name subfolders.")
    return {"dataset": _write_csv(rows, ["path", "label", "sample_rate", "channels", "duration_seconds"]),
            "metadata": {"modality": "audio", "clips": len(rows), "classes": sorted({r["label"] for r in rows})}}


